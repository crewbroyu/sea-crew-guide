import fs from 'node:fs'
import process from 'node:process'
import interviewQuestions from '../src/data/interviewQuestions.js'
import { isApproved, parseCsv } from './lib/referenceAnswerCsv.mjs'

// Turns reviewed rows (approved = Y / 是) from content/reference-answers/*.csv into one SQL file to
// paste into the Supabase SQL Editor. Rows that are not approved are skipped; edited answers replace
// earlier imports. Usage: npm run import:reference-answers -- restaurant housekeeping front_office

const POSITIONS = ['restaurant', 'housekeeping', 'front_office', 'bar_server', 'retail']
const dir = new URL('../content/reference-answers/', import.meta.url)
const positions = process.argv.slice(2).length ? process.argv.slice(2) : POSITIONS.filter((key) => fs.existsSync(new URL(`${key}.csv`, dir)))
const literal = (value) => (value ? `'${String(value).replace(/'/g, "''")}'` : 'null')

const values = []
const problems = []
for (const positionKey of positions) {
  if (!POSITIONS.includes(positionKey)) throw new Error(`Unknown position ${positionKey}`)
  const knownIds = new Set((interviewQuestions[positionKey]?.questions || []).map((question) => question.id))
  const rows = parseCsv(fs.readFileSync(new URL(`${positionKey}.csv`, dir), 'utf8'))
  let approved = 0
  for (const row of rows) {
    if (!isApproved(row.approved)) continue
    if (row.position_key !== positionKey || !knownIds.has(row.question_id)) problems.push(`${positionKey}: unknown question ${row.question_id}`)
    else if (!row.answer_en || row.answer_en.length > 2000) problems.push(`${positionKey} ${row.question_id}: answer missing or over 2000 characters`)
    else if (row.key_points_zh.length > 1000) problems.push(`${positionKey} ${row.question_id}: key points over 1000 characters`)
    else {
      values.push(`  (${literal(positionKey)}, ${literal(row.question_id)}, ${literal(row.answer_en)}, ${literal(row.key_points_zh)})`)
      approved += 1
    }
  }
  console.log(`${positionKey}: ${approved} approved of ${rows.length}`)
}

if (problems.length) {
  console.error(problems.join('\n'))
  process.exit(1)
}
if (!values.length) {
  console.error('No approved rows. Mark reviewed rows with Y or 是 in the approved column.')
  process.exit(1)
}

const sql = `-- Generated by scripts/import-reference-answers.mjs. Paste into the Supabase SQL Editor.
begin;
insert into public.interview_reference_answers (position_key, question_id, answer_en, key_points_zh)
values
${values.join(',\n')}
on conflict (position_key, question_id) do update set
  answer_en = excluded.answer_en,
  key_points_zh = excluded.key_points_zh,
  reviewed_at = now(),
  updated_at = now();
commit;
select position_key, count(*) as answers from public.interview_reference_answers group by position_key order by position_key;
`
const out = new URL('import.sql', dir)
fs.writeFileSync(out, sql)
console.log(`Wrote ${values.length} answers to content/reference-answers/import.sql`)
