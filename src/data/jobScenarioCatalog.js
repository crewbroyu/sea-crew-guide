export const getScenarioById = (scenarioId) =>
  barServerSimulationScenarios.find((scenario) => scenario.id === scenarioId) || null

export const getScenarioForWeakSkill = (skillKey, completedScenarioIds = []) => {
  const uncompleted = barServerSimulationScenarios.filter((scenario) => !completedScenarioIds.includes(scenario.id))
  const candidates = uncompleted.length ? uncompleted : barServerSimulationScenarios
  return candidates.find((scenario) => scenario.evaluationFocus.includes(skillKey)) || candidates[0]
}
